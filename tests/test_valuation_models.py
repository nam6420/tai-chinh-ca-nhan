from __future__ import annotations

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "learning" / "practice" / "models"))

import valuation as v  # noqa: E402


class SoBaiHoc(unittest.TestCase):
    def test_010_wacc_va_beta(self):
        ke = v.capm(0.03, 1.2, 0.05)
        self.assertAlmostEqual(v.wacc(ke, 0.05, 0.25, 70, 30), 0.07425, places=6)
        self.assertAlmostEqual(v.wacc(ke, 0.05, 0.0, 70, 30), 0.078, places=6)
        bu = v.unlever(1.3, 0.5, 0.25)
        self.assertAlmostEqual(bu, 0.9455, places=4)
        self.assertAlmostEqual(v.relever(bu, 1.0, 0.25), 1.6545, places=4)
        self.assertAlmostEqual(v.convert_rate(0.04, 0.025, 0.04), 0.0552, places=4)

    def test_011_apple_dcf(self):
        a = v.load_apple()
        self.assertEqual(a["Gross margin"], a["Net sales - Total"]
                         - a["Cost of sales - Products"] - a["Cost of sales - Services"])
        fcf0 = a["Cash generated by operating activities"] - a["Payments for PP&E"] \
            - a["Share-based compensation"]
        self.assertEqual(fcf0, 85904)
        r = v.dcf(fcf0, [.06, .055, .05, .045, .04], .088, .03)
        self.assertAlmostEqual(r["ev"], 1667254, delta=1)
        self.assertAlmostEqual(r["tv_share"], 0.766, places=3)
        self.assertAlmostEqual(v.per_share(r["ev"], 33763, 14776.353), 115.12, places=2)
        self.assertAlmostEqual(
            v.per_share(v.dcf(fcf0, [.06, .055, .05, .045, .04], .098, .03)["ev"],
                        33763, 14776.353), 98.4, places=1)

    def test_011_dao_chieu(self):
        g = v.implied_growth(85904, 150 * 14776.353 - 33763, .088, .03)
        self.assertAlmostEqual(g, 0.1145, places=3)

    def test_011_wacc_ham_y(self):
        g = [.06, .055, .05, .045, .04]
        sh, net = 14776.353, 33763
        for price, exp in ((150, .0744), (345, .0492)):
            w = v.implied_wacc(85904, g, .03, price * sh - net)
            self.assertAlmostEqual(w, exp, places=3)

    def test_012_kich_ban(self):
        args = (85904,)
        sc = {"bat": ([.02] * 5, .098, .02, 78.3),
              "thuan": ([.09, .085, .08, .07, .06], .083, .035, 153.2)}
        for _, (g, w, gt, exp) in sc.items():
            p = v.per_share(v.dcf(*args, g, w, gt)["ev"], 33763, 14776.353)
            self.assertAlmostEqual(p, exp, places=1)

    def test_f1_ba_bao_cao_can_doi(self):
        base = dict(revenue=1000, ppe=300, ar=50, inv=120, ap=100, debt=150,
                    cash=100, equity=320)
        a = dict(growth=.08, gross_margin=.30, opex_pct=.18, dep_rate=.10, rate=.06,
                 tax=.20, dso=18.25, dio=120 / 700 * 365, dpo=100 / 700 * 365,
                 capex_pct=.06, repay=20, payout=.4)
        rows = v.three_statement(base, a)
        for r in rows:
            self.assertAlmostEqual(r["check"], 0, places=9)
        self.assertAlmostEqual(rows[0]["cash"], 83.1, places=1)
        self.assertAlmostEqual(rows[2]["cash"], 54.5, places=1)
        stress = v.three_statement(base, {**a, "growth": .12, "capex_pct": .09, "payout": .6})
        self.assertLess(stress[2]["cash"], 0)

    def test_chan_dieu_kien_ke_lon_hon_g(self):
        with self.assertRaises(ValueError):
            v.gordon(4, .03, .03)
        with self.assertRaises(ValueError):
            v.dcf(100, [.05], .03, .04)

    def test_f2(self):
        self.assertAlmostEqual(v.gordon(4, .10, .03), 57.142857, places=5)
        self.assertAlmostEqual(v.ddm_two_stage(3, .08, 5, .03, .10), 54.47, places=2)
        r = v.residual_income(1000, [.18, .16, .14, .13, .12], .12, .4)
        self.assertAlmostEqual(r["value"], 1114.56, places=2)
        self.assertAlmostEqual(v.residual_income(1000, [.12] * 5, .12, .4)["value"], 1000, places=6)
        self.assertEqual(v.sotp([("A", 80, 7), ("B", 40, 10), ("tru so", -20, 7)]), 820)


if __name__ == "__main__":
    unittest.main()
